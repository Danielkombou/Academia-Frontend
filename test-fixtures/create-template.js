const { createCanvas } = require('canvas');
const fs = require('fs');

// Create a simple certificate template: landscape A4 at 150 DPI
const width = 1485;  // 297mm * 150/25.4 ≈ 1754, but let's use a reasonable size
const height = 1050; // 210mm * 150/25.4 ≈ 1240

const canvas = createCanvas(width, height);
const ctx = canvas.getContext('2d');

// Background
ctx.fillStyle = '#f5f5f5';
ctx.fillRect(0, 0, width, height);

// Border
ctx.strokeStyle = '#4faf83';
ctx.lineWidth = 8;
ctx.strokeRect(20, 20, width - 40, height - 40);

// Title
ctx.fillStyle = '#1f2847';
ctx.font = 'bold 48px sans-serif';
ctx.textAlign = 'center';
ctx.fillText('CERTIFICATE OF ACHIEVEMENT', width / 2, height / 2 - 60);

// Decorative line
ctx.strokeStyle = '#4faf83';
ctx.lineWidth = 3;
ctx.beginPath();
ctx.moveTo(width / 2 - 150, height / 2 - 30);
ctx.lineTo(width / 2 + 150, height / 2 - 30);
ctx.stroke();

// Subtitle
ctx.fillStyle = '#666';
ctx.font = '24px sans-serif';
ctx.fillText('This certifies that', width / 2, height / 2 + 20);

// Name placeholder area (will be replaced)
ctx.fillStyle = '#ddd';
ctx.fillRect(width / 2 - 200, height / 2 + 40, 400, 60);
ctx.strokeStyle = '#999';
ctx.lineWidth = 2;
ctx.strokeRect(width / 2 - 200, height / 2 + 40, 400, 60);

// Footer
ctx.fillStyle = '#999';
ctx.font = '16px sans-serif';
ctx.fillText('Generated by Veni Certificate Generator', width / 2, height - 40);

const buffer = canvas.toBuffer('image/png');
fs.writeFileSync('/home/afuhflynn/Projects/veni/test-fixtures/template.png', buffer);
fs.writeFileSync('/home/afuhflynn/Projects/veni-react/test-fixtures/template.png', buffer);
console.log('Template created:', width, 'x', height);
